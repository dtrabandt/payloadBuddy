func TestMiddleware_Disabled(t *testing.T) {
	cfg := Setup(false, "", "")
	called := false
	next := http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) { called = true })

	req := httptest.NewRequest("GET", "/", nil)
	w := httptest.NewRecorder()
	cfg.Middleware(next)(w, req)

	if !called {
		t.Error("Expected next handler to be called when auth is disabled")
	}
}

func TestMiddleware_Enabled_NoCredentials(t *testing.T) {
	cfg := Setup(true, "admin", "secret")

	req := httptest.NewRequest("GET", "/", nil)
	w := httptest.NewRecorder()
	cfg.Middleware(func(w http.ResponseWriter, r *http.Request) {})(w, req)

	if w.Code != http.StatusUnauthorized {
		t.Errorf("Expected 401, got %d", w.Code)
	}
	if w.Header().Get("WWW-Authenticate") == "" {
		t.Error("Expected WWW-Authenticate header")
	}
}

func TestMiddleware_Enabled_WrongCredentials(t *testing.T) {
	cfg := Setup(true, "admin", "secret")

	req := httptest.NewRequest("GET", "/", nil)
	req.SetBasicAuth("admin", "wrong")
	w := httptest.NewRecorder()
	cfg.Middleware(func(w http.ResponseWriter, r *http.Request) {})(w, req)

	if w.Code != http.StatusUnauthorized {
		t.Errorf("Expected 401, got %d", w.Code)
	}
}

func TestMiddleware_Enabled_CorrectCredentials(t *testing.T) {
	cfg := Setup(true, "admin", "secret")
	called := false
	next := http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) { called = true })

	req := httptest.NewRequest("GET", "/", nil)
	req.SetBasicAuth("admin", "secret")
	w := httptest.NewRecorder()
	cfg.Middleware(next)(w, req)

	if !called {
		t.Error("Expected next handler to be called with correct credentials")
	}
	if w.Code != http.StatusOK {
		t.Errorf("Expected 200, got %d", w.Code)
	}
}
