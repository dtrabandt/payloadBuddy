func TestGenerateRandomString(t *testing.T) {
	tests := []struct {
		name   string
		length int
	}{
		{"short string", 8},
		{"medium string", 12},
		{"long string", 32},
		{"single character", 1},
	}

	const charset = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789"
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			result := generateRandomString(tt.length)
			if len(result) != tt.length {
				t.Errorf("expected length %d, got %d", tt.length, len(result))
			}
			for _, ch := range result {
				if !strings.ContainsRune(charset, ch) {
					t.Errorf("invalid character %q in generated string", ch)
				}
			}
			if tt.length > 1 {
				seen := make(map[string]bool)
				for range 10 {
					s := generateRandomString(tt.length)
					if seen[s] {
						t.Errorf("generated duplicate string: %s", s)
					}
					seen[s] = true
				}
			}
		})
	}
}

func TestGenerateRandomString_Uniqueness(t *testing.T) {
	seen := make(map[string]bool)
	for i := range 100 {
		s := generateRandomString(16)
		if seen[s] {
			t.Errorf("duplicate string after %d iterations: %s", i+1, s)
		}
		seen[s] = true
	}
}

func TestSetup_Disabled(t *testing.T) {
	cfg := Setup(false, "", "")
	if cfg.Enabled {
		t.Error("expected Enabled=false")
	}
	if cfg.Username != "" || cfg.Password != "" {
		t.Error("expected empty credentials when auth is disabled")
	}
}

func TestSetup_AutoGenerated(t *testing.T) {
	cfg := Setup(true, "", "")
	if !cfg.Enabled {
		t.Error("expected Enabled=true")
	}
	if len(cfg.Username) != 8 {
		t.Errorf("expected auto-generated username length 8, got %d", len(cfg.Username))
	}
	if len(cfg.Password) != 12 {
		t.Errorf("expected auto-generated password length 12, got %d", len(cfg.Password))
	}
}

func TestSetup_CustomCredentials(t *testing.T) {
	cfg := Setup(true, "admin", "secret123")
	if cfg.Username != "admin" {
		t.Errorf("expected username 'admin', got %q", cfg.Username)
	}
	if cfg.Password != "secret123" {
		t.Errorf("expected password 'secret123', got %q", cfg.Password)
	}
}

